#!/usr/bin/env bash
# Regenerate the hash-pinned PyTorch requirement files that
# scripts/install.sh installs with `pip install --require-hashes -r`.
#
#   python/torch-linux-x86_64.txt   CUDA 12.6 wheels (download.pytorch.org/whl/cu126)
#   python/torch-macos-arm64.txt    CPU/MPS wheels   (download.pytorch.org/whl/cpu)
#
# Both are for CPython 3.10, the interpreter install.sh creates the venv
# with. uv resolves each platform from this host (no wheel is installed), and
# takes every sha256 from the index's published `#sha256=` fragment.
#
# To move the pin, change the three versions below to another matched set
# AND add that set to `matchedSets` in tests/ttorch_pins.nim, which refuses
# any triple it does not know. Then rerun this script and commit the result.
#
# Run from inside `nix develop` (the flake provides uv).

set -euo pipefail

TORCH=2.11.0
TORCHVISION=0.26.0
TORCHAUDIO=2.11.0

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# uv records the hash of every wheel of a version, for every platform and
# Python. For the torch family, keep only the one wheel this file is for, and
# name its URL: the hash comes from the index's `#sha256=` fragment for that
# wheel, and must be one of the hashes uv recorded.
narrow() {
  python3 -I - "$1" "$2" "$3" <<'PY'
import re
import sys
import urllib.request

out, index, wheel_tag = sys.argv[1:]
text = open(out).read()
for name in ("torch", "torchvision", "torchaudio"):
    m = re.search(rf"^{name}==(\S+) \\\n((?:    --hash=sha256:[0-9a-f]{{64}}(?: \\)?\n)+)", text, re.M)
    if not m:
        sys.exit(f"lock-torch: no {name} stanza in {out}")
    version = m.group(1)
    page = urllib.request.urlopen(f"{index}/{name}/").read().decode()
    wheel = f"{name}-{version.replace('+', '%2B')}-cp310-cp310-{wheel_tag}.whl"
    hit = re.search(rf'href="([^"#]*/{re.escape(wheel)})#sha256=([0-9a-f]{{64}})"', page)
    if not hit:
        sys.exit(f"lock-torch: {wheel} is not on {index}/{name}/")
    url, digest = hit.groups()
    if digest not in m.group(2):
        sys.exit(f"lock-torch: {wheel}'s sha256 is not among the hashes uv recorded")
    stanza = f"# {url}\n{name}=={version} \\\n    --hash=sha256:{digest}\n"
    text = text[: m.start()] + stanza + text[m.end():]
open(out, "w").write(text)
PY
}

lock() {
  local out="$1" index="$2" platform="$3" local_tag="$4" wheel_tag="$5"
  local spec
  spec="$(mktemp)"
  printf 'torch==%s%s\ntorchvision==%s%s\ntorchaudio==%s%s\n' \
    "$TORCH" "$local_tag" "$TORCHVISION" "$local_tag" "$TORCHAUDIO" "$local_tag" > "$spec"
  {
    echo "# GENERATED by scripts/lock-torch.sh; do not edit by hand."
    echo "# PyTorch $TORCH / torchvision $TORCHVISION / torchaudio $TORCHAUDIO,"
    echo "# CPython 3.10, $platform. Every hash is the sha256 the index publishes."
    echo "# Installed by scripts/install.sh with pip --require-hashes."
    echo "--index-url $index"
    echo "--extra-index-url https://pypi.org/simple"
    echo
    # The pytorch index first, so the torch family (and the CUDA runtime
    # wheels it hosts) come from it; PyPI for everything it does not carry.
    uv pip compile "$spec" --quiet --no-header --no-annotate --generate-hashes \
      --python-version 3.10 --python-platform "$platform" \
      --index "$index" --default-index https://pypi.org/simple \
      --no-emit-index-url --no-python-downloads
  } > "$out"
  rm -f "$spec"
  narrow "$out" "$index" "$wheel_tag"
  echo "[lock-torch] wrote $out"
}

lock python/torch-linux-x86_64.txt https://download.pytorch.org/whl/cu126 x86_64-manylinux_2_28 +cu126 manylinux_2_28_x86_64
lock python/torch-macos-arm64.txt https://download.pytorch.org/whl/cpu aarch64-apple-darwin "" macosx_11_0_arm64
